<?php

namespace SystemTestFramework\Generators;

use Illuminate\Support\Str;

class DeepApiTestGenerator
{
    /**
     * Generate an automated Feature Test for a REST API endpoint.
     */
    public function generateApiTest(string $className, array $routeMeta, ?array $validationRules): string
    {
        $uri = $routeMeta['uri'];
        $methods = $routeMeta['methods'];
        $method = $methods[0] ?? 'GET';
        $requiresAuth = $routeMeta['requires_auth'];

        $authSetup = $requiresAuth
            ? "\$token = \$this->getSyntheticApiBearerToken();\n        \$headers = ['Authorization' => \"Bearer {\$token}\", 'Accept' => 'application/json'];"
            : "\$headers = ['Accept' => 'application/json'];";

        $unauthScenario = '';
        if ($requiresAuth) {
            $unauthScenario = <<<PHP

    /**
     * SCENARIO 1: Security Barrier - Unauthenticated Request
     * @test
     */
    public function test_01_unauthenticated_request_is_blocked(): void
    {
        \$response = \$this->withHeaders(['Accept' => 'application/json'])
            ->{$this->resolveTestCall($method, $uri)};

        \$this->assertContains(\$response->status(), [401, 403], 'Unauthenticated request must be blocked with 401 or 403.');
    }
PHP;
        }

        $validationScenario = '';
        if (in_array($method, ['POST', 'PUT', 'PATCH']) && !empty($validationRules)) {
            $validationScenario = <<<PHP

    /**
     * SCENARIO 2: Payload Validation & Contract Boundary
     * @test
     */
    public function test_02_empty_payload_fails_validation(): void
    {
        {$authSetup}

        \$response = \$this->withHeaders(\$headers)
            ->{$this->resolveTestCall($method, $uri, '[]')};

        \$this->assertEquals(422, \$response->status(), 'Empty payload to {$uri} must yield 422 Unprocessable Entity.');
        \$response->assertJsonStructure(['message']);
    }
PHP;
        }

        return <<<PHP
<?php

namespace Tests\Feature\DeepQA\Api;

use Tests\TestCase;
use App\Models\User;

/**
 * 360° REST API Contract Test
 * Endpoint: {$method} {$uri}
 * Auto-generated by Autonomous Laravel System-Test Framework
 */
class {$className} extends TestCase
{
{$unauthScenario}
{$validationScenario}

    /**
     * SCENARIO 3: Response Structure & Schema Integrity Contract
     * @test
     */
    public function test_03_endpoint_response_structure_contract(): void
    {
        {$authSetup}

        \$response = \$this->withHeaders(\$headers)
            ->{$this->resolveTestCall($method, $uri)};

        \$this->assertNotEquals(500, \$response->status(), 'API endpoint {$uri} must not produce 500 Internal Server Error.');
        
        // Assert no sensitive database column leakage
        \$content = \$response->getContent();
        \$this->assertStringNotContainsString('password_hash', \$content);
        \$this->assertStringNotContainsString('SQLSTATE', \$content);
    }

    protected function getSyntheticApiBearerToken(): string
    {
        \$user = User::first() ?? User::factory()->create();
        return method_exists(\$user, 'createToken')
            ? \$user->createToken('system-test')->accessToken ?? 'synthetic-token'
            : 'synthetic-token';
    }
}
PHP;
    }

    protected function resolveTestCall(string $method, string $uri, string $payload = '[]'): string
    {
        $methodLower = strtolower($method);
        if (in_array($methodLower, ['post', 'put', 'patch'])) {
            return "json('{$method}', '{$uri}', {$payload})";
        }
        return "getJson('{$uri}')";
    }
}

